import { tableAccessFetch as fetch } from './table-access-fixture';
import assert from 'node:assert/strict';
import { AuthClient, type StaffFixture } from './staff-http';
import { realtimeTest } from './realtime-transport';
import { ServiceCall, Restaurant, Table, TableSession } from '../src/models';
import type { ServiceCallDto, ServiceSnapshot } from '../src/types/service-calls';
export async function runServiceHttpChecks(base: string, fixture: StaffFixture) {
  const staff = new AuthClient(base); await staff.login(fixture.email, fixture.password);
  const path = '/api/r/salt/tables/6';
  const post = (endpoint: string, body: unknown, cookie = '') => fetch(`${base}${endpoint}`, { method: 'POST', headers: { cookie, Origin: base, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const session = await post(`${path}/session`, {});
  const cookie = session.headers.get('set-cookie')!.split(';')[0];
  const { visitId } = await session.json() as { visitId: string };
  const endpoint = `${path}/service-calls`;
  assert.equal((await post(endpoint, { type: 'WAITER' })).status, 401);
  assert.equal((await fetch(`${base}${endpoint}`)).status, 401);
  assert.equal((await post('/api/r/salt/tables/5/service-calls', { type: 'WAITER' }, cookie)).status, 401);
  assert.equal((await post(endpoint, { type: 'WAITER', tableSessionId: visitId }, cookie)).status, 400);
  assert.equal((await fetch(`${base}${endpoint}?tableSessionId=${visitId}`, { headers: { cookie } })).status, 400);
  assert.equal((await fetch(`${base}/api/dashboard/service-calls`)).status, 401);
  const before = realtimeTest.events.length;
  const races = await Promise.all(Array.from({ length: 4 }, () => post(endpoint, { type: 'WAITER' }, cookie)));
  const calls = await Promise.all(races.map(async response => { assert.equal(response.status, 200); return await response.json() as { call: ServiceCallDto; alreadyPending: boolean }; }));
  assert.equal(new Set(calls.map(item => item.call.id)).size, 1);
  assert.equal(calls.filter(item => !item.alreadyPending).length, 1);
  assert.equal(realtimeTest.events.length, before + 1);
  const waiter = calls[0].call;
  const event = realtimeTest.events.at(-1)!;
  assert.equal(event.name, 'serviceCall.created'); assert.deepEqual(JSON.parse(event.data), { version: 1 });
  assert.ok(event.committed.some(item => item.id === waiter.id && item.status === 'PENDING'));
  const bill = await (await post(endpoint, { type: 'BILL' }, cookie)).json() as { call: ServiceCallDto };
  realtimeTest.failNext = true;
  const helpResponse = await post(endpoint, { type: 'HELP' }, cookie); assert.equal(helpResponse.status, 200);
  const help = await helpResponse.json() as { call: ServiceCallDto };
  assert.equal(await ServiceCall.countDocuments({ tableSessionId: visitId, status: 'PENDING' }), 3);
  const update = (id: string, expectedStatus: string, status: string) => staff.request(`/api/dashboard/service-calls/${id}`, { method: 'PATCH', headers: { Origin: base, 'Content-Type': 'application/json' }, body: JSON.stringify({ expectedStatus, status }) });
  assert.equal((await update(waiter.id, 'PENDING', 'ACKNOWLEDGED')).status, 200);
  const acknowledged = await ServiceCall.findById(waiter.id).orFail(); assert.ok(acknowledged.acknowledgedAt);
  assert.equal(realtimeTest.events.at(-1)!.name, 'serviceCall.updated');
  assert.ok(realtimeTest.events.at(-1)!.committed.some(item => item.id === waiter.id && item.status === 'ACKNOWLEDGED'));
  assert.equal((await update(waiter.id, 'ACKNOWLEDGED', 'RESOLVED')).status, 200);
  const cooldown = await post(endpoint, { type: 'WAITER' }, cookie); assert.equal(cooldown.status, 429); assert.ok(cooldown.headers.get('retry-after'));
  assert.equal((await update(waiter.id, 'RESOLVED', 'PENDING')).status, 422);
  assert.equal((await update('invalid', 'PENDING', 'RESOLVED')).status, 400);
  const concurrent = await Promise.all([update(bill.call.id, 'PENDING', 'ACKNOWLEDGED'), update(bill.call.id, 'PENDING', 'RESOLVED')]);
  assert.deepEqual(concurrent.map(response => response.status).sort(), [200, 409]);
  realtimeTest.failNext = true;
  assert.equal((await update(help.call.id, 'PENDING', 'RESOLVED')).status, 200);
  assert.equal((await ServiceCall.findById(help.call.id).orFail()).status, 'RESOLVED');
  // Age only this disposable fixture, exercising the boundary without a 30-second sleep.
  await ServiceCall.collection.updateOne({ _id: acknowledged._id }, { $set: { createdAt: new Date(Date.now() - 31_000) } });
  const repeated = await (await post(endpoint, { type: 'WAITER' }, cookie)).json() as { call: ServiceCallDto };
  assert.notEqual(repeated.call.id, waiter.id);
  const old = await ServiceCall.findById(waiter.id).orFail(); assert.equal(old.status, 'RESOLVED'); assert.ok(old.resolvedAt); assert.equal(old.acknowledgedAt?.toISOString(), acknowledged.acknowledgedAt?.toISOString());
  const other = await Restaurant.findOne({ slug: 'other' }).orFail();
  const table = await Table.findOne({ restaurantId: other._id }).orFail();
  const visit = await TableSession.findOne({ restaurantId: other._id, tableId: table._id, status: 'ACTIVE' }).orFail();
  const foreign = await ServiceCall.create({ restaurantId: other._id, tableId: table._id, tableSessionId: visit._id, type: 'BILL' });
  assert.equal((await update(String(foreign._id), 'PENDING', 'RESOLVED')).status, 404);
  assert.equal((await update('000000000000000000000001', 'PENDING', 'RESOLVED')).status, 404);
  const snapshot = await (await staff.request('/api/dashboard/service-calls')).json() as ServiceSnapshot;
  assert.equal(snapshot.calls.some(call => call.id === String(foreign._id)), false);
  assert.equal(snapshot.calls.find(call => call.id === waiter.id)?.status, 'RESOLVED');
  const own = await (await fetch(`${base}${endpoint}`, { headers: { cookie } })).json() as { calls: ServiceCallDto[] };
  assert.equal(own.calls.length, 3); assert.equal(own.calls.some(call => call.id === String(foreign._id)), false);
  await TableSession.updateOne({ _id: visitId }, { $set: { status: 'CLOSED', closedAt: new Date() } });
  const notices = realtimeTest.events.length;
  assert.equal((await post(endpoint, { type: 'WAITER' }, cookie)).status, 409);
  assert.equal((await fetch(`${base}${endpoint}`, { headers: { cookie } })).status, 409);
  assert.equal(realtimeTest.events.length, notices);
  console.log('PASS: service authorization, per-type duplicate/cooldown concurrency, all transitions, tenant isolation, timestamps/history and post-commit realtime failure resilience.');
}
