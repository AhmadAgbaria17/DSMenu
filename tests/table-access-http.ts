import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { Table, TableSession, Restaurant } from '../src/models';
import { AuthClient, type StaffFixture } from './staff-http';
import { newCustomerToken, tokenHash, customerCookieName } from '../src/lib/customer-security';
import type { TableSnapshot } from '../src/types/tables';
import { createStaffUser } from '../src/lib/staff-users';

export async function runTableAccessChecks(base: string, fixture: StaffFixture) {
  await createStaffUser({ restaurant: 'salt', name: 'Access HTTP Staff', email: 'access-http@salt.local', password: fixture.password, role: 'STAFF' });
  const staff = new AuthClient(base); await staff.login('access-http@salt.local', fixture.password);
  const table = await Table.create({ restaurantId: fixture.restaurantId, tableNumber: 410 });
  const endpoint = `${base}/api/r/salt/tables/410/session`;
  const get = async (cookie = '') => (await fetch(endpoint, { headers: { cookie } })).json();
  const post = (data: unknown, cookie = '', url = endpoint) => fetch(url, { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json', cookie }, body: JSON.stringify(data) });
  const close = (id: string) => staff.request(`/api/dashboard/tables/${table._id}/close`, { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json' }, body: JSON.stringify({ sessionId: id }) });
  const row = async () => (await (await staff.request('/api/dashboard/tables')).json() as TableSnapshot).tables.find(t => t.id === String(table._id))!;
  assert.deepEqual(await get(), { mode: 'CREATE' });
  assert.equal(await TableSession.countDocuments({ tableId: table._id }), 0, 'checking entry does not create visits');
  assert.equal((await post({})).status, 403, 'empty POST cannot bypass code entry');
  for (const code of ['12', '1234', 'abc', 527]) assert.equal((await post({ action: 'CREATE', code })).status, 400);
  const first = await post({ action: 'CREATE', code: '527' }); assert.equal(first.status, 200);
  const cookieA = first.headers.getSetCookie()[0].split(';')[0];
  const { visitId: a } = await first.json() as { visitId: string };
  assert.deepEqual(await get(), { mode: 'JOIN', sessionId: a });
  assert.deepEqual(await get(cookieA), { mode: 'AUTHORIZED', visitId: a });
  assert.equal((await post({ action: 'JOIN', code: '527', sessionId: a })).status, 200, 'second device joins A');
  assert.equal((await row()).visit?.accessCode, '527');
  assert.equal((await TableSession.findById(a).lean())?.accessCode, undefined, 'ordinary queries exclude code');
  const protectedBase = endpoint.replace('/session', '');
  assert.equal((await post({ clientRequestId: randomUUID(), items: [{ productId: '123456789012345678901234', quantity: 1, note: '' }] }, '', protectedBase + '/orders')).status, 401);
  assert.equal((await post({ type: 'WAITER' }, '', protectedBase + '/service-calls')).status, 401);
  assert.equal((await close(a)).status, 200);
  assert.equal((await TableSession.findById(a).select('+accessCode').lean())?.accessCode, undefined);
  assert.equal((await post({}, cookieA)).status, 403);
  assert.equal((await post({ action: 'JOIN', code: '527', sessionId: a })).status, 409);
  assert.equal((await post({ type: 'WAITER' }, cookieA, protectedBase + '/service-calls')).status, 409);
  assert.deepEqual(await get(cookieA), { mode: 'CREATE' });
  const second = await post({ action: 'CREATE', code: '314' }, cookieA); assert.equal(second.status, 200);
  const { visitId: b } = await second.json() as { visitId: string }; assert.notEqual(b, a);
  assert.equal((await post({ action: 'JOIN', code: '314', sessionId: b })).status, 200);
  assert.equal((await post({ action: 'JOIN', code: '527', sessionId: b })).status, 403);
  assert.equal((await post({ action: 'JOIN', code: '314', sessionId: a })).status, 409, 'stale form cannot join later visit');
  assert.equal((await row()).visit?.accessCode, '314');
  assert.equal((await post({}, cookieA)).status, 403, 'old credential cannot resume B');
  assert.equal((await fetch(protectedBase + '/orders', { headers: { cookie: cookieA } })).status, 409);
  for (let n = 0; n < 4; n++) assert.equal((await post({ action: 'JOIN', code: '000', sessionId: b })).status, 403);
  assert.equal((await post({ action: 'JOIN', code: '314', sessionId: b })).status, 429);
  assert.equal((await TableSession.findById(b).select('+codeAttemptCount').lean())?.codeAttemptCount, 5, 'incorrect attempts commit in MongoDB');
  await TableSession.updateOne({ _id: b }, { $set: { codeAttemptWindowAt: new Date(Date.now() - 301000) } });
  assert.equal((await post({ action: 'JOIN', code: '314', sessionId: b })).status, 200, 'cooldown expires, never permanently locks');
  const other = await Restaurant.findOne({ slug: 'other' }).orFail();
  await Table.create({ restaurantId: other._id, tableNumber: 410 });
  const foreign = endpoint.replace('/salt/', '/other/');
  assert.equal((await post({ action: 'JOIN', code: '314', sessionId: b }, '', foreign)).status, 409);
  await createStaffUser({ restaurant: 'other', name: 'Other Access Staff', email: 'access-http@other.local', password: fixture.password, role: 'STAFF' });
  const otherStaff = new AuthClient(base); await otherStaff.login('access-http@other.local', fixture.password);
  const foreignRows = await (await otherStaff.request('/api/dashboard/tables')).json() as TableSnapshot;
  assert.equal(foreignRows.tables.some(t => t.id === String(table._id) || t.visit?.id === b), false, 'foreign staff cannot retrieve this session or its code');
  assert.equal((await fetch(base + '/api/dashboard/tables')).status, 401);
  const publicHtml = await (await fetch(base + '/r/salt?table=410')).text();
  assert.doesNotMatch(publicHtml, /"accessCode"|"credentials"|"tokenHash"/);
  assert.equal((await close(b)).status, 200);
  const raced = await Promise.all(['027', '999'].map(code => post({ action: 'CREATE', code })));
  assert.deepEqual(raced.map(r => r.status).sort(), [200, 409]);
  const winner = await TableSession.findOne({ tableId: table._id, status: 'ACTIVE' }).select('+accessCode').orFail();
  assert.equal(winner.accessCode, raced[0].status === 200 ? '027' : '999');
  assert.equal(await TableSession.countDocuments({ tableId: table._id, status: 'ACTIVE' }), 1);
  assert.equal(raced.find(r => r.status === 409)!.headers.get('set-cookie'), null);
  await TableSession.collection.updateOne({ _id: winner._id }, { $set: { createdAt: new Date(Date.now() - 121 * 60000), lastActivityAt: new Date(Date.now() - 121 * 60000) } });
  assert.deepEqual(await get(), { mode: 'CREATE' }, 'automatic empty cleanup also resets code');
  assert.equal((await TableSession.findById(winner._id).select('+accessCode').lean())?.accessCode, undefined);
  // A legacy occupied visit can only acquire its first code through an existing credential.
  const token = newCustomerToken();
  const legacy = await TableSession.create({ restaurantId: fixture.restaurantId, tableId: table._id, credentials: [{ tokenHash: tokenHash(token), expiresAt: new Date(Date.now() + 60000) }] });
  const legacyCookie = `${customerCookieName(fixture.restaurantId, 410)}=${token}`;
  assert.deepEqual(await get(), { mode: 'WAIT' });
  assert.equal((await post({ action: 'SETUP', code: '027', sessionId: String(legacy._id) })).status, 401);
  assert.deepEqual(await get(legacyCookie), { mode: 'SETUP', sessionId: String(legacy._id) });
  assert.equal((await post({ action: 'SETUP', code: '027', sessionId: String(legacy._id) }, legacyCookie)).status, 200);
  assert.equal((await row()).visit?.accessCode, '027');
  assert.equal((await close(String(legacy._id))).status, 200);
  console.log('PASS: table access create/join, 527 -> close -> 314 reset, credential revocation, stale forms, race, persistent cooldown, tenant isolation, legacy setup and auto-cleanup.');
}
